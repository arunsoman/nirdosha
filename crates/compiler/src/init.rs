/// `run.sh` contents -- `main.rs::cmd_init` writes this with the exec bit
/// set (a plain `fs::write` doesn't set it).
pub fn render_launcher_unix(project_name: &str) -> String {
    format!(
        r#"#!/bin/sh
# Starts {project_name}'s server: `nirdosha serve`, exposing the UI at
# GET / and the API at POST /api/<fn>.
#
# --jwks-file/--issuer/--audience below are placeholders (jwks.json holds
# an empty key set) -- the server starts and non-gated routes work as-is,
# but every `requires(role: ...)` route 401s until you replace them with
# a real identity provider's values. Delete all three flags entirely to
# run with no auth configured instead.
cd "$(dirname "$0")"
./nirdosha serve {project_name}.nir \
  --host 127.0.0.1 --port 8080 \
  --jwks-file jwks.json --issuer https://REPLACE_ME_ISSUER --audience REPLACE_ME_AUDIENCE \
  --db {project_name}.db
"#
    )
}

/// `run.bat` contents -- the Windows counterpart to `render_launcher_unix`.
pub fn render_launcher_windows(project_name: &str) -> String {
    format!(
        r#"@echo off
rem Starts {project_name}'s server: `nirdosha serve`, exposing the UI at
rem GET / and the API at POST /api/<fn>.
rem
rem --jwks-file/--issuer/--audience below are placeholders (jwks.json
rem holds an empty key set) -- the server starts and non-gated routes
rem work as-is, but every `requires(role: ...)` route 401s until you
rem replace them with a real identity provider's values. Delete all
rem three flags entirely to run with no auth configured instead.
cd /d "%~dp0"
nirdosha.exe serve {project_name}.nir --host 127.0.0.1 --port 8080 --jwks-file jwks.json --issuer https://REPLACE_ME_ISSUER --audience REPLACE_ME_AUDIENCE --db {project_name}.db
"#
    )
}

/// `jwks.json` contents -- an empty, syntactically valid key set so
/// `serve`'s `--jwks-file` starts successfully with no manual setup;
/// every `requires(role: ...)` route still honestly 401s (no key can
/// ever validate a token) until it's replaced with real IdP keys.
pub fn placeholder_jwks() -> &'static str {
    "{\"keys\": []}\n"
}
